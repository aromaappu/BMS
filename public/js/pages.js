let lastReport = null;
let reportRequestId = 0;
async function generateReport() {
  const result = document.getElementById('reportResult');
  if (!result) return;
  const type = document.getElementById('reportType').value;
  const from = document.getElementById('reportFrom').value;
  const to = document.getElementById('reportTo').value;
  if (!from || !to || from > to) {
    result.innerHTML = '<p class="chart-empty">Choose a valid date range (start date before end date).</p>';
    return;
  }
  const requestId = ++reportRequestId;
  result.innerHTML = '<p class="chart-empty">Loading report…</p>';
  try {
    const d = await apiGet(`reports.php?type=${encodeURIComponent(type)}&from=${encodeURIComponent(from)}&to=${encodeURIComponent(to)}`);
    if (requestId !== reportRequestId || window.activeBmsPage !== 'reports') return;
    if (!d.ok) { result.innerHTML = '<p class="chart-empty">Report unavailable. Please try again.</p>'; return; }
    lastReport = d;
    bmsCharts.destroy('reportChart');
    result.innerHTML = `
      <div class="row">
        <section class="card chart-card">
          <div class="chart-head"><div><h3>Performance by ${escapeHtml(type)}</h3><p class="chart-subtitle">${escapeHtml(from)} to ${escapeHtml(to)}</p></div>
            <span class="chart-badge">${d.labels.length} ENTRIES</span>
          </div>
          <div class="chart-container"><canvas id="reportChart" role="img" aria-label="Sales report chart"></canvas></div>
        </section>
        <section class="card">
          <div class="chart-head"><div><h3>Report breakdown</h3><p class="chart-subtitle">Total amount: <strong>${money(d.total)}</strong></p></div></div>
          <div class="table-wrap" style="max-height:355px;overflow:auto">
            <table><thead><tr><th>Category / period</th><th>Amount</th></tr></thead>
              <tbody>${d.labels.length ? d.labels.map((l, i) => `<tr><td>${escapeHtml(l)}</td><td><strong>${money(d.values[i])}</strong></td></tr>`).join('') :
                '<tr><td colspan="2" class="table-empty">No transactions in this date range</td></tr>'}</tbody>
            </table>
          </div>
        </section>
      </div>
    `;
    let labels = d.labels.slice(), values = d.values.slice();
    const isRing = ['payment', 'category'].includes(type);
    const horizontal = ['product', 'customer'].includes(type);
    if (isRing && labels.length > 7) {
      labels = labels.slice(0, 7).concat('Other');
      values = values.slice(0, 7).concat(d.values.slice(7).reduce((sum, n) => sum + Number(n || 0), 0));
    }
    if (horizontal) { labels = labels.slice(0, 9); values = values.slice(0, 9); }
    bmsCharts.create('reportChart', isRing ? 'doughnut' : ['daily','monthly'].includes(type) ? 'line' : 'bar',
      labels, values, { label: 'Revenue', horizontal, color: '#4f46e5' });
  } catch (error) {
    if (requestId === reportRequestId && window.activeBmsPage === 'reports') {
      result.innerHTML = '<p class="chart-empty">Unable to load the report. Check your connection and try again.</p>';
    }
  }
}

function exportCSV() {
  if (!lastReport) { toast('Generate a report first', 'warning'); return; }
  const quote = cell => {
    let s = String(cell ?? '');
    if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
    return '"' + s.replace(/"/g, '""') + '"';
  };
  let csv = '\uFEFFLabel,Value\r\n';
  lastReport.labels.forEach((label, i) => { csv += quote(label) + ',' + Number(lastReport.values[i] || 0) + '\r\n'; });
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = 'bms_report_' + new Date().toISOString().split('T')[0] + '.csv';
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  toast('Report exported');
}

