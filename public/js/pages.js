function bmsMetricRows(items, muted = false) {
  if (!items?.length) return '<tr><td colspan="2" class="table-empty">No product data yet</td></tr>';
  const max = Math.max(1, ...items.map(item => Number(item.q) || 0));
  return items.map(item => {
    const q = Math.max(0, Number(item.q) || 0);
    const percent = Math.min(100, q / max * 100);
    return `<tr><td><strong>${escapeHtml(item.name)}</strong></td><td>
      <span class="metric-bar"><span class="metric-bar-fill ${muted ? 'muted' : ''}" style="width:${percent}%"></span></span>
      <span class="metric-value">${q.toLocaleString('en-IN')}</span>
    </td></tr>`;
  }).join('');
}

